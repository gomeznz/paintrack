import * as Crypto from "expo-crypto";
import * as SecureStore from "expo-secure-store";
import * as SQLite from "expo-sqlite";
import { migrate } from "./records";

/**
 * Opens the on-device database, encrypted with SQLCipher.
 *
 * The 256-bit database key is generated on first run and kept in the iOS
 * Keychain / Android Keystore, readable only while the phone is unlocked and
 * never included in backups or transferred to another device
 * (WHEN_UNLOCKED_THIS_DEVICE_ONLY). A copy of the database file on its own,
 * e.g. from a backup, is unreadable.
 */

const DB_NAME = "paintrack.db";
const KEY_NAME = "paintrack.db-key.v1";
const KEY_OPTIONS: SecureStore.SecureStoreOptions = {
  keychainAccessible: SecureStore.WHEN_UNLOCKED_THIS_DEVICE_ONLY,
};

export class DatabaseUnavailableError extends Error {
  constructor(
    message: string,
    /** True when the stored data can't be decrypted and only a reset helps. */
    readonly resettable: boolean,
  ) {
    super(message);
    this.name = "DatabaseUnavailableError";
  }
}

function toHex(bytes: Uint8Array): string {
  return Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
}

async function getKey(): Promise<{ key: string; isNew: boolean }> {
  const existing = await SecureStore.getItemAsync(KEY_NAME, KEY_OPTIONS);
  if (existing) return { key: existing, isNew: false };
  const key = toHex(Crypto.getRandomBytes(32));
  await SecureStore.setItemAsync(KEY_NAME, key, KEY_OPTIONS);
  return { key, isNew: true };
}

async function openWithKey(key: string): Promise<SQLite.SQLiteDatabase> {
  // The key is generated by us as hex, so it is safe to inline; check anyway
  // because PRAGMA statements can't take bound parameters.
  if (!/^[0-9a-f]{64}$/.test(key)) throw new DatabaseUnavailableError("Stored key is malformed", true);

  const db = await SQLite.openDatabaseAsync(DB_NAME);
  try {
    await db.execAsync(`PRAGMA key = "x'${key}'";`);
    // Fail closed: refuse to store anything if SQLCipher isn't actually
    // compiled in (e.g. the useSQLCipher plugin option was dropped).
    const cipher = await db.getFirstAsync<{ cipher_version: string }>("PRAGMA cipher_version", []);
    if (!cipher?.cipher_version) {
      throw new DatabaseUnavailableError("Database encryption is not available in this build", false);
    }
    // Throws "file is not a database" if the key is wrong.
    await db.getFirstAsync("SELECT count(*) FROM sqlite_master", []);
    await db.execAsync("PRAGMA foreign_keys = ON; PRAGMA secure_delete = ON;");
    await migrate(db);
    return db;
  } catch (error) {
    await db.closeAsync().catch(() => {});
    throw error;
  }
}

export async function openDatabase(): Promise<SQLite.SQLiteDatabase> {
  const { key, isNew } = await getKey();
  try {
    return await openWithKey(key);
  } catch (error) {
    if (error instanceof DatabaseUnavailableError) throw error;
    if (isNew) {
      // A database file without its key (e.g. restored onto a new phone) can
      // never be decrypted. Nothing to lose by starting fresh.
      await SQLite.deleteDatabaseAsync(DB_NAME).catch(() => {});
      return openWithKey(key);
    }
    throw new DatabaseUnavailableError("Your records couldn't be unlocked on this device", true);
  }
}

/** Irreversibly deletes all records and the key that protects them. */
export async function eraseEverything(db?: SQLite.SQLiteDatabase): Promise<void> {
  await db?.closeAsync().catch(() => {});
  await SQLite.deleteDatabaseAsync(DB_NAME).catch(() => {});
  await SecureStore.deleteItemAsync(KEY_NAME, KEY_OPTIONS);
}
